import {readFile} from "node:fs/promises";
import Decimal from "decimal.js";
import {expect,it} from "vitest";
import {apiResponse,AnalysisResponse,CatalogResponse,ComparisonRequest,ComparisonResponse,SpatialContext} from "@/lib/contracts";
const base=process.env.LIVE_BASE_URL??"http://localhost:3000";
it("round-trips real Gemini typed tools through the unmocked localhost production API",async()=>{
 const catalog=apiResponse(CatalogResponse).parse(await(await fetch(`${base}/api/v1/properties`)).json());
 if(!catalog.ok)throw Error(`Catalog failed: ${catalog.error.code}`);
 expect(catalog.data.properties.length===1).toBe(true);
 const input=ComparisonRequest.parse(JSON.parse(await readFile("sponsor-data/runtime/reviewed-scenarios.json","utf8")));
 expect(input.propertyId===catalog.data.properties[0].id).toBe(true);
 const spatial=apiResponse(SpatialContext).parse(await(await fetch(`${base}/api/v1/properties/${encodeURIComponent(input.propertyId)}/spatial`)).json());
 if(!spatial.ok)throw Error(`Spatial retrieval failed: ${spatial.error.code}`);
 expect(spatial.data.match.status==="verified"&&spatial.data.model?.commercialPropertyId===input.propertyId).toBe(true);
 expect(spatial.data.model?.showcase?.sid===spatial.data.model?.id).toBe(true);
 const post=async(path:string,data:unknown)=>{const response=await fetch(base+path,{method:"POST",headers:{"content-type":"application/json",origin:new URL(base).origin},body:JSON.stringify(data)});return response.json()};
 input.inputRevision=81;input.constraints.maxInitialInvestment.value="999999999";
 const first=apiResponse(ComparisonResponse).parse(await post("/api/v1/scenarios/compare",input));
 if(!first.ok)throw Error(`Comparison failed: ${first.error.code}`);
 expect(first.data.comparison.preferredScenarioId==="alternative-b").toBe(true);
 const a=input.scenarios.find(s=>s.id==="alternative-a")!;
 input.constraints.maxInitialInvestment.value=Object.values(a.capex).reduce((sum,d)=>sum.plus(d.value??"0"),new Decimal(0)).times("1.1").toFixed();
 input.inputRevision++;
 const changed=apiResponse(ComparisonResponse).parse(await post("/api/v1/scenarios/compare",input));
 if(!changed.ok)throw Error(`Edited comparison failed: ${changed.error.code}`);
 expect(changed.data.comparison.preferredScenarioId==="alternative-a").toBe(true);
 const incomplete=structuredClone(input);incomplete.inputRevision++;incomplete.scenarios[1].annualRentPerSqft.value=null;
 const missing=apiResponse(AnalysisResponse).parse(await post("/api/v1/analysis",{...incomplete,action:"analyze"}));
 expect(missing.ok&&missing.data.status==="needs_input"&&missing.data.scenarios[1].annualRentPerSqft.value===null).toBe(true);
 input.inputRevision+=2;
 const canonical=apiResponse(ComparisonResponse).parse(await post("/api/v1/scenarios/compare",input));
 if(!canonical.ok)throw Error(`Final comparison failed: ${canonical.error.code}`);
 const result=apiResponse(AnalysisResponse).parse(await post("/api/v1/analysis",{...input,action:"analyze"}));
 if(!result.ok)throw Error(`Live analysis failed: ${result.error.code}`);
 expect(result.data.status==="complete").toBe(true);
 if(result.data.status!=="complete")throw Error("Live analysis needs more inputs.");
 const data=result.data;
 expect(data.execution.requestId===result.requestId&&data.property.id===input.propertyId&&data.inputRevision===input.inputRevision).toBe(true);
 expect(JSON.stringify(data.comparison)===JSON.stringify(canonical.data.comparison)).toBe(true);
 expect(["write_todos","getPropertyContext","proposeScenarios","runComparison"].every(name=>data.execution.completedTools.some(t=>t.name===name&&t.toolCallId.length>0))).toBe(true);
 expect(data.summary.claims.some(c=>c.evidenceIds.length>0&&c.kind==="fact")).toBe(true);
 const evidence=new Set(data.evidence.map(e=>e.id));expect(data.summary.claims.every(c=>c.evidenceIds.every(id=>evidence.has(id)))).toBe(true);
 expect(data.modelUsage.provider==="gemini"&&data.execution.elapsedMs<=60000).toBe(true);
 console.info("Real localhost workflow verified",{budgetAdaptation:true,requestCorrelation:true,sourceReferences:true,needsInputRecovery:true,model:data.modelUsage.modelId,attempts:data.modelUsage.attempts,elapsedMs:data.execution.elapsedMs,dataMode:data.execution.dataMode});
},90000);
